#!/usr/bin/env python3
"""Compile Intel's authentic CMAA2 HLSL to Vulkan SPIR-V arrays at build time.

The reference source remains Intel's, with a targeted alpha-preserving store
change. The game uses alpha as data in HDR post-processing; Intel's D3D sample
writes zero alpha on touched edges. This version preserves source alpha.
"""
import argparse
from pathlib import Path
import shutil
import struct
import subprocess
import urllib.request

SOURCE = ('https://raw.githubusercontent.com/GameTechDev/CMAA2/master/'
          'Projects/CMAA2/CMAA2/CMAA2.hlsl')
ENTRIES = {
    'EDGES': 'EdgesColor2x2CS',
    'ARGS': 'ComputeDispatchArgsCS',
    'CANDIDATES': 'ProcessCandidatesCS',
    'APPLY': 'DeferredColorApply2x2CS',
}

def main():
    p = argparse.ArgumentParser()
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--dxc', required=True)
    p.add_argument('--source', type=Path, default=None,
                   help='Optional local copy of Intel CMAA2.hlsl (for offline builds)')
    args = p.parse_args()
    dest = args.output.resolve()
    dest.parent.mkdir(parents=True, exist_ok=True)
    text = (args.source.read_text(encoding='utf-8-sig') if args.source else
            urllib.request.urlopen(SOURCE, timeout=60).read().decode('utf-8-sig'))
    original = 'g_inoutColorWriteonly[ pixelPos ] = lpfloat4( color.rgb, 0 );'
    changed = ('g_inoutColorWriteonly[ pixelPos ] = lpfloat4( color.rgb, '
               'g_inoutColorReadonly.Load( int3( pixelPos, 0 ) ).a );')
    if text.count(original) != 1:
        raise RuntimeError('Intel CMAA2 source changed: alpha-preserving patch cannot apply')
    text = text.replace(original, changed)
    # DXC's Vulkan SPIR-V backend requires Texture2D.Load's optional offset
    # operand to be a compile-time constant. Intel's LoadSourceColor passes a
    # runtime int2 offset; fold it into the signed texel coordinates instead.
    # This is equivalent for the single-sample Texture2D path used here.
    offset_load = 'g_inoutColorReadonly.Load( int3( pixelPos, 0 ), offset ).rgb'
    direct_load = 'g_inoutColorReadonly.Load( int3( int2(pixelPos) + offset, 0 ) ).rgb'
    if text.count(offset_load) != 1:
        raise RuntimeError('Intel CMAA2 source changed: dynamic texture-load rewrite cannot apply')
    text = text.replace(offset_load, direct_load)
    # Compile a separate opt-in LDR final-apply diagnostic shader. It writes
    # magenta only where DeferredColorApply2x2CS actually stores a blended pixel.
    # The normal HDR/LDR variants are unchanged.
    store_start = 'void FinalUAVStore( uint2 pixelPos, lpfloat3 color )\n{'
    if text.count(store_start) != 1:
        raise RuntimeError('Intel CMAA2 source changed: debug apply patch cannot apply')
    text = text.replace(
        store_start,
        store_start + '\n#if defined(BB_CMAA2_DEBUG_APPLY)\n'
        '    color = lpfloat3( 1.0, 0.0, 1.0 );\n#endif',
    )
    source_file = dest.parent / 'CMAA2.bbport.hlsl'
    source_file.write_text(text, encoding='utf-8')
    rows = ['// Autogenerated from Intel CMAA2 HLSL; do not edit', '#pragma once', '#include <cstdint>']
    for fmt in ('HDR', 'LDR'):
        # LDR_APPLY_DEBUG is deliberately an extra shader, not a replacement.
        # Running normally never activates it.
        variants = list(ENTRIES.items())
        if fmt == 'LDR':
            variants.append(('APPLY_DEBUG', ENTRIES['APPLY']))
        for name, entry in variants:
            spirv = dest.parent / f'cmaa2_{fmt.lower()}_{name.lower()}.spv'
            cmd = [args.dxc, '-spirv', '-T', 'cs_6_0', '-E', entry,
                   '-fspv-target-env=vulkan1.3',
                   '-fvk-u-shift', '0', 'all', '-fvk-t-shift', '8', 'all',
                   '-DCMAA2_UAV_STORE_TYPED=1',
                   '-DCMAA2_UAV_STORE_CONVERT_TO_SRGB=0',
                   *(['-DBB_CMAA2_DEBUG_APPLY=1'] if name == 'APPLY_DEBUG' else []),
                   f'-DCMAA2_UAV_STORE_TYPED_UNORM_FLOAT={0 if fmt == "HDR" else 1}',
                   f'-DCMAA2_SUPPORT_HDR_COLOR_RANGE={1 if fmt == "HDR" else 0}',
                   '-DCMAA2_EDGE_DETECTION_LUMA_PATH=1',
                   # CMAA2 Ultra quality (preset 3): threshold 0.05 vs High's 0.07.
                   '-DCMAA2_STATIC_QUALITY_PRESET=3',
                   '-DCMAA_MSAA_SAMPLE_COUNT=1',
                   '-Fo', str(spirv), str(source_file)]
            subprocess.run(cmd, check=True)
            val = shutil.which('spirv-val')
            if val:
                subprocess.run([val, '--target-env', 'vulkan1.3', str(spirv)], check=True)
            binary = spirv.read_bytes()
            if len(binary) % 4 or binary[:4] != b'\x03\x02#\x07':
                raise RuntimeError(f'Invalid SPIR-V generated for {entry}')
            words = struct.unpack('<' + 'I' * (len(binary) // 4), binary)
            rows += [f'inline constexpr std::uint32_t CMAA2_{fmt}_{name}[] = {{']
            for i in range(0, len(words), 8):
                rows += ['    ' + ', '.join(f'0x{w:08x}u' for w in words[i:i+8]) + ',']
            rows += ['};']
    dest.write_text('\n'.join(rows) + '\n', encoding='utf-8')

if __name__ == '__main__':
    main()
